// Least-squares fit of the compressibility factor Z of O2, N2 and He to the NIST reference
// data in scripts/nist/*.tsv (scripts/fetch-nist.sh). Writes src/lib/compressibility-coefficients.ts,
// used by Z() in src/lib/formulas.ts. Run after refreshing the data:
//   npm run nist:fit
//
// Model (per gas):  Z(P, T) - 1 = sum over i = 1..4, j = 0..2 of  c[i][j] * p^i * t^j
//   p = P / 100 bar (absolute),  t = (T - 288.15 K) / 100 K
// Fitted on 1..351 bar absolute and 263.15..333.15 K (-10..+60 °C), the range blending uses.
// Z from the data: Z = P / (rho * R * T).
import { readFileSync, writeFileSync } from 'node:fs';

const R = 0.0831446261815324; // L·bar/(mol·K), CODATA 2018 exact value of R
const P_MAX = 351;
const ORDER_P = 4;
const ORDER_T = 2;

/** Solves A x = b (Gauss-Jordan with partial pivoting).
 * @param {number[][]} A
 * @param {number[]} b */
function solve(A, b) {
	const n = b.length;
	const M = A.map((row, i) => [...row, b[i]]);
	for (let i = 0; i < n; i++) {
		let p = i;
		for (let r = i + 1; r < n; r++) if (Math.abs(M[r][i]) > Math.abs(M[p][i])) p = r;
		[M[i], M[p]] = [M[p], M[i]];
		for (let r = 0; r < n; r++) {
			if (r === i) continue;
			const f = M[r][i] / M[i][i];
			for (let c = i; c <= n; c++) M[r][c] -= f * M[i][c];
		}
	}
	return M.map((row, i) => row[n] / row[i]);
}

/** @param {number} T @param {number} P */
const features = (T, P) => {
	const t = (T - 288.15) / 100;
	const p = P / 100;
	const f = [];
	for (let i = 1; i <= ORDER_P; i++) for (let j = 0; j <= ORDER_T; j++) f.push(p ** i * t ** j);
	return f;
};

/** @type {Record<string, number[][]>} */
const out = {};
const report = [];
for (const gas of ['O2', 'N2', 'He']) {
	const rows = readFileSync(new URL(`nist/${gas}.tsv`, import.meta.url), 'utf8')
		.trim()
		.split('\n')
		.map((line) => line.split('\t').map(Number))
		.filter(([, P]) => P <= P_MAX);
	const X = rows.map(([T, P]) => features(T, P));
	const y = rows.map(([T, P, rho]) => P / (rho * R * T) - 1);
	const n = X[0].length;
	const AtA = Array.from({ length: n }, () => Array(n).fill(0));
	const Aty = Array(n).fill(0);
	X.forEach((x, r) => {
		for (let i = 0; i < n; i++) {
			Aty[i] += x[i] * y[r];
			for (let j = 0; j < n; j++) AtA[i][j] += x[i] * x[j];
		}
	});
	const c = solve(AtA, Aty);
	let max = 0;
	X.forEach((x, r) => {
		const fit = x.reduce((s, v, i) => s + v * c[i], 0);
		max = Math.max(max, Math.abs(fit - y[r]) / (1 + y[r]));
	});
	const matrix = [];
	for (let i = 0; i < ORDER_P; i++) matrix.push(c.slice(i * (ORDER_T + 1), (i + 1) * (ORDER_T + 1)));
	out[gas] = matrix;
	report.push(`${gas}: ${rows.length} points, max relative error ${(max * 100).toFixed(3)} %`);
}

const ts = `// GENERATED by scripts/fit-compressibility.js from the NIST data in scripts/nist/ — do not edit.
// Coefficients c[i-1][j] of  Z(P, T) - 1 = sum c[i-1][j] * (P/100 bar)^i * ((T - 288.15 K)/100 K)^j
// (P absolute), valid for 1..${P_MAX} bar and 263.15..333.15 K. Fit quality against the NIST data:
${report.map((line) => `//   ${line}`).join('\n')}
export const Z_COEFFICIENTS = ${JSON.stringify(out, null, '\t')} as const;

export const Z_MAX_ERROR = ${JSON.stringify(report)};
`;
writeFileSync(new URL('../src/lib/compressibility-coefficients.ts', import.meta.url), ts);
console.log(report.join('\n'));
